"""drop the global participants table

Revision ID: 0018_drop_participants
Revises: 0017_add_display_name
Create Date: 2026-11-19 00:00:00.000000

Studies are independent: a participant belongs to a study, and the same
participant id in two studies does not denote the same person. The global
``participants`` table was a registry of ids with a first-seen timestamp; it is
the only table that made an id mean something across studies, so it goes.

``study_participants`` already carries everything a participant has: the join
date (``created_at``), display name, consent, instructions, submission and skip
state, and the browser snapshot. ``activities`` and
``study_external_task_assignments`` keep their ``participant_id`` columns as
plain study-scoped strings.

The three foreign keys are dropped first. Their names were generated by the
database when 0001 created the tables, so they are looked up through the
inspector instead of being hard-coded (PostgreSQL, MariaDB and MSSQL name them
differently).

A database built from the current models (``create_all``, which is what the
integration tests do) never had the table; the guard keeps the adoption path
working for it.
"""

